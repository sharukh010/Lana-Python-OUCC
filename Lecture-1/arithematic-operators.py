num1 = 8
num2 = 2 

# addition -> + 
print(num1 + num2) # 10 

# subtraction -> - 
print(num1 - num2)# 6

# multiplication -> * 
print(num1 * num2) # 16 

# division -> / 
print(5/2) # 2.5 

#floor division -> // 
print(5//2) # 2 

# modulo division -> % (remainder)
print(5%2) # 1 

# power -> **
print(2**3) #8 